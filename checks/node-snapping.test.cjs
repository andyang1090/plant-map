const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('dist/workspace-options.js','utf8');
const objects=[{id:'wall',type:'wall',x:100,y:200,w:100,h:50,points:[[0,0],[1,0],[1,1]]},{id:'room',type:'room',x:20,y:30,w:40,h:40}];
const context={items:()=>objects,page:'workshop',data:{axes:true},camera:{w:1000},svg:{getBoundingClientRect:()=>({width:1000})}};
context.orthogonalActive=e=>!!(context.data.preferences?.orthogonal||e?.shiftKey);vm.createContext(context);vm.runInContext(source.slice(source.indexOf('function drawingNodes'),source.indexOf('const snapIndicator')),context);
assert.equal(context.nearestDrawingNode({x:103,y:202}).x,100);
assert.equal(context.nearestDrawingNode({x:199,y:251}).y,250);
assert.equal(context.nearestDrawingNode({x:103,y:202},new Set(['wall'])),null);
assert.equal(context.nearestDrawingNode({x:22,y:31}).x,20);
assert.equal(context.nearestDrawingNode({x:500,y:500}),null);
objects.push({id:'h',type:'haxis',y:400},{id:'v',type:'vaxis',x:300});
assert.equal(context.nearestDrawingNode({x:303,y:404}).x,300);
assert.equal(context.nearestDrawingNode({x:303,y:404}).y,400);
assert.equal(context.nearestDrawingNode({x:303,y:404},new Set(['h'])),null);
context.data.axes=false;
assert.equal(context.nearestDrawingNode({x:303,y:404}),null);
context.data.axes=true;objects.find(o=>o.id==='v').hidden=true;
assert.equal(context.nearestDrawingNode({x:303,y:404}),null);
console.log('Wall endpoints, corners, exclusions and screen-distance snapping passed.');
// The first wall vertex must snap after grid rounding, before sketch exists.
objects.splice(0,objects.length,{id:'h',type:'haxis',y:200.75},{id:'v',type:'vaxis',x:100.25});
Object.assign(context,{sketch:null,snap:true,gridStep:50,rawPoint:e=>({...e}),rawBeforeNodeSnap:e=>({...e}),indicateSnap:()=>{}});
const shapes=fs.readFileSync('dist/shapes.js','utf8');
vm.runInContext(shapes.slice(shapes.indexOf('function sketchPoint'),shapes.indexOf('function sketchPaint')),context);
let first=context.sketchPoint({x:103,y:203});
assert.equal(first.x,100.25);assert.equal(first.y,200.75);
let onLine=context.sketchPoint({x:400,y:204});
assert.equal(onLine.y,200.75,'First point also snaps along an axis away from a crossing');
context.sketch={vertices:[{x:0,y:0}]};
assert.equal(context.sketchPoint({x:103,y:203}).y,200.75,'Later vertices keep identical precision');
context.snap=false;
assert.equal(context.sketchPoint({x:103,y:203}).y,203);
