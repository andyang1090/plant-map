assert.equal(dragged.x,100.25,'Dragging must keep the exact crossing X after grid rounding');
assert.equal(dragged.y,200.75,'Dragging must keep the exact crossing Y after grid rounding');
const free=context.resolveWallVertex({x:103.12,y:203.45,altKey:true},{x:0,y:0});
assert.equal(free.x,103.12);assert.equal(free.y,203.45);
context.data.axes=false;
assert.equal(context.resolveWallVertex({x:103,y:203},{x:0,y:0}).y,200,'Hidden axes cannot override grid snapping');
console.log('Wall vertex dragging keeps exact intersections and two-decimal coordinates.');
