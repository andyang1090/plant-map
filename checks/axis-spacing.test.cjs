const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('dist/axis-spacing.js','utf8');
const context={data:{preferences:{}},tool:'haxis',rawPoint:e=>e,items:()=>[{type:'haxis',y:100}],freeAxis:()=>({free:true})};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function axisSpacing'),source.indexOf('const spacingLabel'))+source.slice(source.indexOf('smartAxis=function'),source.indexOf('const spacingRender')),context);
assert.equal(context.smartAxis({x:0,y:113}).y,115);
assert.equal(context.smartAxis({x:0,y:900}).y,115,'Next axis uses exactly one spacing even at low zoom');
assert.equal(context.smartAxis({x:0,y:86}).y,85);
context.data.preferences.axisSpacing=20;
assert.equal(context.smartAxis({x:0,y:118}).y,120);
assert.equal(context.smartAxis({altKey:true}).free,true);
context.tool='vaxis';context.items=()=>[{type:'vaxis',x:50}];
assert.equal(context.smartAxis({x:68,y:0}).x,70);
context.items=()=>[];
assert.equal(context.smartAxis({x:12.3,y:0}).x,12.3);
context.tool='haxis';context.data.preferences.axisSpacing=15;
context.items=()=>[{type:'haxis',name:'A',y:-700},{type:'haxis',name:'B',y:-685},{type:'haxis',name:'G',y:-610}];
assert.equal(context.smartAxis({x:0,y:-710}).y,-715,'Insert above A rather than above last-created G');
assert.equal(context.smartAxis({x:0,y:-710}).reference,'A');
context.data.preferences.axisSpacing=7.5;
assert.equal(context.smartAxis({x:0,y:-696}).y,-692.5,'Insert between A and B with a smaller spacing');
context.items=()=>[{type:'haxis',name:'A',y:100},{type:'haxis',name:'hidden',y:112,hidden:true},{type:'haxis',name:'C',y:200},{type:'vaxis',name:'1',x:113}];
assert.equal(context.smartAxis({x:0,y:113}).reference,'A','Ignore hidden and perpendicular axes');
context.tool='vaxis';context.data.preferences.axisSpacing=15;
context.items=()=>[{type:'vaxis',name:'1',x:100},{type:'vaxis',name:'2',x:200},{type:'vaxis',name:'3',x:300}];
assert.equal(context.smartAxis({x:90,y:0}).x,85,'Insert left of the nearest vertical axis');
assert.equal(context.smartAxis({x:210,y:0}).x,215,'Use middle axis instead of last-created one');
context.data.preferences.axisSpacing=7.25;
assert.equal(context.smartAxis({x:210,y:0}).x,207.25,'Keep two decimal places in the placed coordinate');
context.data.preferences.axisSpacing=.01;
assert.equal(context.smartAxis({x:210,y:0}).x,200.01,'Allow a one-centimetre spacing');
console.log('Default/custom axis spacing, both directions and free positioning passed.');
const workspace=fs.readFileSync('dist/workspace-options.js','utf8');
const integration={smartAxis:()=>({h:true,y:115,value:115}),snap:true,tool:'haxis',items:()=>[{type:'haxis',y:100}],nearestDrawingNode:()=>({x:0,y:200}),rawBeforeNodeSnap:e=>e,indicateSnap:()=>{}};
vm.createContext(integration);
vm.runInContext(workspace.slice(workspace.indexOf('const axisWithNodeSnap'),workspace.indexOf('const moveWithNodes')),integration);
assert.equal(integration.smartAxis({}).y,115,'Node snapping must not override explicit axis spacing');
integration.items=()=>[];
assert.equal(integration.smartAxis({}).y,200,'First axis can still snap to a wall node');
console.log('Axis/node snapping precedence regression passed.');
